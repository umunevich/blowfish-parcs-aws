#!/usr/bin/env python3
"""Generate src/blowfish_constants.py from the hexadecimal digits of pi.

Blowfish initialises its P-array (18 words) and four S-boxes (4 x 256 words)
with the fractional part of pi written in hexadecimal: 18 + 1024 = 1042
32-bit words = 8336 hex digits. Instead of copying the tables from somewhere,
we compute pi ourselves with Machin's formula using big integers:

    pi = 16 * arctan(1/5) - 4 * arctan(1/239)

Usage:
    python3 scripts/gen_pi_constants.py            # writes src/blowfish_constants.py
"""
import os

WORDS = 18 + 4 * 256
GUARD_BITS = 64  # extra precision to absorb truncation errors


def arctan_inv(x, one):
    """arctan(1/x) * one, computed with the Taylor series in fixed point."""
    total = term = one // x
    x2 = x * x
    n = 1
    sign = -1
    while term:
        term //= x2
        total += sign * (term // (2 * n + 1))
        sign = -sign
        n += 1
    return total


def pi_fraction_words(count):
    """Return the first `count` 32-bit words of the fractional part of pi."""
    bits = 32 * count + GUARD_BITS
    one = 1 << bits
    pi = 16 * arctan_inv(5, one) - 4 * arctan_inv(239, one)
    frac = (pi - 3 * one) >> GUARD_BITS  # drop the integer part "3" and guard bits
    words = []
    for i in range(count):
        shift = 32 * (count - 1 - i)
        words.append((frac >> shift) & 0xFFFFFFFF)
    return words


def format_table(name, words):
    lines = ["%s = [" % name]
    for i in range(0, len(words), 4):
        lines.append("    " + ", ".join("0x%08X" % w for w in words[i:i + 4]) + ",")
    lines.append("]")
    return "\n".join(lines)


def main():
    words = pi_fraction_words(WORDS)
    # Sanity checks against the well-known first/last values of the tables.
    assert words[0] == 0x243F6A88, hex(words[0])
    assert words[18] == 0xD1310BA6, hex(words[18])
    assert words[-1] == 0x3AC372E6, hex(words[-1])

    p_array = words[:18]
    s_boxes = [words[18 + 256 * k: 18 + 256 * (k + 1)] for k in range(4)]

    parts = [
        '"""Blowfish initial constants: hexadecimal digits of pi.',
        "",
        "AUTO-GENERATED by scripts/gen_pi_constants.py -- do not edit by hand.",
        '"""',
        "",
        format_table("PI_P_ARRAY", p_array),
        "",
    ]
    for k in range(4):
        parts.append(format_table("PI_S_BOX_%d" % k, s_boxes[k]))
        parts.append("")
    parts.append("PI_S_BOXES = [PI_S_BOX_0, PI_S_BOX_1, PI_S_BOX_2, PI_S_BOX_3]")
    parts.append("")

    out_path = os.path.join(os.path.dirname(__file__), "..", "src", "blowfish_constants.py")
    with open(out_path, "w") as f:
        f.write("\n".join(parts))
    print("Wrote %s (%d words)" % (os.path.normpath(out_path), WORDS))


if __name__ == "__main__":
    main()
